Value1 = [10, 20, 30 ,40 , 10]  # List - List Are Mutable(Changeable) 
print(Value1)
print(type(Value1))

Value2 = (10, 20, 30 ,40 , 10)   # Tuple - Tuple Are Immutable(Not Changeable)
print(Value2)
print(type(Value2))

Value3 = {10, 20, 30 ,40 , 10}    # Set - Mutable (But Not Accept Duplicate Values )
print(Value3)
print(type(Value3))

